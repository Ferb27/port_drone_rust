#!/usr/bin/env python3
"""Generate crates/de_common/src/messages.rs from droneengage_common messages.hpp.

Every `#define NAME value` with a number or string literal becomes a Rust const.
Trailing `// comment` becomes a doc comment. Re-run whenever upstream changes:

  python3 tools/gen_messages/gen_messages.py \
      ../de_upstream_oct_2026/droneengage_common/de_databus/messages.hpp \
      crates/de_common/src/messages.rs <upstream-sha>
"""
import re
import sys

src, dst, sha = sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "unknown"
DEF = re.compile(r'^\s*#define\s+(\w+)\s+(-?(?:0x[0-9a-fA-F]+|\d+)[uUlL]*|"(?:[^"\\]|\\.)*")\s*(?://\s*(.*))?$')

out = [
    f"// Ported from droneengage_common@{sha}: de_databus/messages.hpp",
    "// GENERATED by tools/gen_messages/gen_messages.py - do not edit by hand.",
    "#![allow(non_upper_case_globals, missing_docs, clippy::unreadable_literal)]",
    "",
]
seen, skipped = set(), []
for line in open(src, encoding="utf-8"):
    if not line.lstrip().startswith("#define"):
        continue
    m = DEF.match(line.rstrip("\n"))
    if not m:
        if len(line.split()) > 2:
            skipped.append(line.strip())
        continue
    name, val, comment = m.group(1), m.group(2), (m.group(3) or "").strip()
    if name in seen:
        skipped.append("duplicate " + name)
        continue
    seen.add(name)
    if comment:
        out.append("/// " + comment.replace("*/", "* /"))
    if val.startswith('"'):
        out.append(f"pub const {name}: &str = {val};")
    else:
        num = int(val.rstrip("uUlL"), 0)
        ty = "i32" if -(2**31) <= num < 2**31 else ("u32" if 0 <= num < 2**32 else "i64")
        out.append(f"pub const {name}: {ty} = {val.rstrip('uUlL')};")

open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"{len(seen)} constants -> {dst}")
for s in skipped:
    print("SKIPPED:", s, file=sys.stderr)
